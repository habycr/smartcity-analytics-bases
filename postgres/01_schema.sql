-- SmartCity Analytics | Sprint 1 | PostgreSQL 16
-- Modelo lógico: 8 tablas, 8 PK y 6 FK.
-- Uso: ejecutar en una base smartcity ya creada y vacía, con permisos CREATE
--      sobre el esquema public (por ejemplo, usando pgAdmin Query Tool).
-- Seguridad: NO incluye contraseñas ni destruye tablas existentes.
-- Los scripts de carga deben respetar IDs compartidos con MongoDB.
-- NOTA EPA: fecha_instalacion y organismo.responsable permiten NULL porque
-- el dataset no proporciona necesariamente esos datos verificables.
-- Estado: activo/inactivo corresponde a la clasificación definida en ETL,
-- NO a un diagnóstico confirmado del estado físico del instrumento.

BEGIN;

CREATE TABLE public.ubicacion (
    id_ubicacion  VARCHAR(64) PRIMARY KEY,
    nombre_zona   VARCHAR(150) NOT NULL,
    distrito      VARCHAR(120) NOT NULL,
    latitud       NUMERIC(9,6) NOT NULL,
    longitud      NUMERIC(9,6) NOT NULL,
    CONSTRAINT ck_ubicacion_latitud CHECK (latitud BETWEEN -90 AND 90),
    CONSTRAINT ck_ubicacion_longitud CHECK (longitud BETWEEN -180 AND 180)
);

CREATE TABLE public.categoria_sensor (
    id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_categoria VARCHAR(100) NOT NULL,
    CONSTRAINT uq_categoria_sensor_nombre UNIQUE (nombre_categoria)
);

CREATE TABLE public.tipo_sensor (
    tipo_sensor  VARCHAR(80) PRIMARY KEY,
    id_categoria BIGINT NOT NULL,
    CONSTRAINT fk_tipo_sensor_categoria
        FOREIGN KEY (id_categoria)
        REFERENCES public.categoria_sensor (id_categoria)
        ON DELETE RESTRICT
);

CREATE TABLE public.organismo_responsable (
    id_organismo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(180) NOT NULL,
    responsable  VARCHAR(180) NULL
);

CREATE TABLE public.usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(100) NOT NULL,
    apellido1   VARCHAR(100) NOT NULL,
    apellido2   VARCHAR(100) NULL,
    correo      VARCHAR(254) NOT NULL,
    CONSTRAINT uq_usuario_correo UNIQUE (correo)
);

CREATE TABLE public.variable_medicion (
    id_variable    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_variable VARCHAR(120) NOT NULL,
    unidad_canonica VARCHAR(40) NOT NULL,
    CONSTRAINT uq_variable_medicion_nombre UNIQUE (nombre_variable)
);

CREATE TABLE public.sensor (
    id_sensor         VARCHAR(64) PRIMARY KEY,
    nombre            VARCHAR(150) NOT NULL,
    tipo_sensor       VARCHAR(80) NOT NULL,
    fecha_instalacion DATE NULL,
    estado            VARCHAR(20) NOT NULL,
    id_ubicacion      VARCHAR(64) NOT NULL,
    id_organismo      BIGINT NOT NULL,
    CONSTRAINT ck_sensor_estado CHECK (estado IN ('activo', 'inactivo')),
    CONSTRAINT fk_sensor_tipo
        FOREIGN KEY (tipo_sensor)
        REFERENCES public.tipo_sensor (tipo_sensor)
        ON DELETE RESTRICT,
    CONSTRAINT fk_sensor_ubicacion
        FOREIGN KEY (id_ubicacion)
        REFERENCES public.ubicacion (id_ubicacion)
        ON DELETE RESTRICT,
    CONSTRAINT fk_sensor_organismo
        FOREIGN KEY (id_organismo)
        REFERENCES public.organismo_responsable (id_organismo)
        ON DELETE RESTRICT
);

CREATE TABLE public.medicion (
    id_medicion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sensor   VARCHAR(64) NOT NULL,
    id_variable BIGINT NOT NULL,
    fecha_utc   TIMESTAMPTZ NOT NULL,
    valor       NUMERIC(18,6) NOT NULL,
    fuente      VARCHAR(180) NOT NULL,
    CONSTRAINT fk_medicion_sensor
        FOREIGN KEY (id_sensor)
        REFERENCES public.sensor (id_sensor)
        ON DELETE RESTRICT,
    CONSTRAINT fk_medicion_variable
        FOREIGN KEY (id_variable)
        REFERENCES public.variable_medicion (id_variable)
        ON DELETE RESTRICT
);

COMMENT ON COLUMN public.ubicacion.distrito IS
    'Para EPA AQS, se mapea County Name como aproximación administrativa documentada.';
COMMENT ON COLUMN public.sensor.fecha_instalacion IS
    'Fecha física de instalación, si se conoce; First Year of Data de EPA no es equivalente.';
COMMENT ON COLUMN public.sensor.estado IS
    'Clasificación binaria acordada; la regla ETL debe declararse sin equipararla a estado físico confirmado.';
COMMENT ON COLUMN public.organismo_responsable.responsable IS
    'Significado funcional pendiente de validación; NULL si no hay información verificable.';
COMMENT ON COLUMN public.medicion.fecha_utc IS
    'Instante de observación; carga EPA combina Date GMT y Time GMT con zona UTC.';
COMMENT ON COLUMN public.medicion.valor IS
    'Valor normalizado; política EPA de negativos, calificadores y unidades se define en el ETL.';

COMMIT;
